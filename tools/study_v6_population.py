"""Compare a smaller single-entry Swift and larger populations, without fitting bot signals.

Run prepare once, then run serially through arena_gate.py; report summarizes recorded files.
The news world is held fixed by seed, but counterparties, disclosures and market paths change.
"""
import argparse
import copy
import csv
import hashlib
import json
import math
import os
from pathlib import Path
import statistics as stats
import subprocess
import sys
import time
import tomllib

from build_release import windows_build_budget
from swift_stress import toml_text

ROOT=Path(__file__).resolve().parents[1]
DEFAULT=ROOT/'runs/v6-population-20261019'
BINARY=ROOT/'target/release'/('llm-market.exe' if os.name=='nt' else 'llm-market')


def write(path,value):
    path.write_text(json.dumps(value,ensure_ascii=False,indent=2),encoding='utf-8')


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def prepare(out, source):
    if out.exists():raise SystemExit(f'Refusing to replace {out}')
    out.mkdir(parents=True)
    (out/'before.toml').write_bytes(source.read_bytes())
    base=tomllib.loads(source.read_text(encoding='utf-8'))
    small=copy.deepcopy(base)
    single=next(g for g in small['bots'] if g.get('owner')=='swift-early-single')
    single['cash']//=10;single['shares_each']//=10
    triple=copy.deepcopy(small)
    liquid=copy.deepcopy(small)
    factors={'grid':4,'value':4,'coral':4,'noise':3}
    for cfg,special in [(triple,False),(liquid,True)]:
        for group in cfg['bots']:
            if group['bot']=='swift':continue
            factor=factors.get(group['bot'],2) if special else 3
            group['count']*=factor;group['count_max']*=factor
    conditions={'before':base,'small':small,'triple':triple,'liquid':liquid}
    for key,cfg in conditions.items():
        text=toml_text(cfg).replace('# Generated by tools/swift_stress.py; the original v5 is unchanged.',
                                  '# Frozen candidate for tools/study_v6_population.py.')
        (out/f'{key}.toml').write_text(text,encoding='utf-8')
    plan=dict(ticks=base['ticks'],threads=4,repeats=1,seeds=[7,11,19,25001,25002,25003],
              holdout_seeds=list(range(25101,25113)),conditions=list(conditions),
              files={f'{k}.toml':digest(out/f'{k}.toml') for k in conditions},
              binary_sha256=digest(BINARY),
              bot_sources={str(p.relative_to(ROOT)):digest(p) for p in (ROOT/'crates/bots/src').glob('*.rs')},
              note='Select on liquidity and price stability, not Swift returns. News and fee rules unchanged. Counts and aggregate endowments both grow.')
    write(out/'plan.json',plan)
    print(json.dumps({k:[sum(g['count'] for g in c['bots']),sum(g.get('count_max',g['count']) for g in c['bots'])] for k,c in conditions.items()}),flush=True)


def run(out,conditions,seeds,repeat=0):
    plan=json.loads((out/'plan.json').read_text(encoding='utf-8'))
    binary=BINARY
    assert digest(binary)==plan['binary_sha256'],'Binary changed since preparation'
    for name,sha in plan['bot_sources'].items():assert digest(ROOT/name)==sha,name
    for seed in seeds:
        order=conditions[:]
        shift=(seed+repeat)%len(order)
        for key in order[shift:]+order[:shift]:
            assert digest(out/f'{key}.toml')==plan['files'][f'{key}.toml']
            dest=out/key/f'seed-{seed}-repeat-{repeat}'
            marker=dest.with_suffix('.done.json')
            if marker.exists():
                if json.loads(marker.read_text(encoding='utf-8'))['exit_code']:
                    raise SystemExit(f'Failed run preserved; inspect {marker}')
                continue
            if dest.exists():raise SystemExit(f'Incomplete output preserved: {dest}')
            dest.parent.mkdir(exist_ok=True)
            command=[str(binary),'run',str(out/f'{key}.toml'),'--out',str(dest),
                     '--seed',str(seed),'--threads',str(plan['threads'])]
            started=time.perf_counter()
            with dest.with_suffix('.log').open('w',encoding='utf-8') as f:
                result=subprocess.run(command,cwd=ROOT,stdout=f,stderr=subprocess.STDOUT)
            wall=time.perf_counter()-started
            write(marker,dict(command=command,wall_seconds=wall,exit_code=result.returncode))
            if result.returncode:raise SystemExit(dest.with_suffix('.log').read_text(encoding='utf-8'))
            print(f'{key} seed {seed} repeat {repeat}: {wall:.3f}s',flush=True)


def maximum_rise(rows,window):
    # Each close is a traded tick close, not a carried-forward synthetic print.
    from collections import deque
    lows=deque();best=1.0;at=None
    for tick,price in rows:
        while lows and tick-lows[0][0]>window:lows.popleft()
        if lows:
            ratio=price/lows[0][1]
            if ratio>best:best=ratio;at=[lows[0][0],tick,lows[0][1],price]
        while lows and lows[-1][1]>=price:lows.pop()
        lows.append((tick,price))
    return best,at


def measure(dest):
    r=json.loads((dest/'summary.json').read_text(encoding='utf-8'))
    bars={};rates={}
    with (dest/'bars.csv').open(encoding='utf-8',newline='') as f:
        for row in csv.DictReader(f):
            stock=row['stock'];tick=int(row['tick'])
            rates.setdefault(stock,[]).append((tick,int(row['dividend'])))
            if row['close']:bars.setdefault(stock,[]).append((tick,int(row['close'])))
    stocks=[]
    for name,rows in bars.items():
        metrics={}
        for window in [50,100,500,3000]:
            ratio,at=maximum_rise(rows,window)
            metrics[f'max_rise_{window}']=ratio
            metrics[f'event_{window}']=at
        diffs=[abs(math.log(b[1]/a[1])) for a,b in zip(rows,rows[1:])]
        metrics.update(stock=name,close_max_min=max(p for _,p in rows)/min(p for _,p in rows),
                       close_jump_p99=sorted(diffs)[min(len(diffs)-1,int(len(diffs)*.99))] if diffs else 0,
                       dividend_initial=rates[name][0][1],dividend_final=rates[name][-1][1],
                       dividend_min=min(d for _,d in rates[name]),dividend_max=max(d for _,d in rates[name]))
        stocks.append(metrics)
    depths=[];spreads=[];both=0;samples=0
    with (dest/'books.csv').open(encoding='utf-8',newline='') as f:
        for b in csv.DictReader(f):
            samples+=1
            if b['bid'] and b['ask']:
                both+=1;bid=int(b['bid']);ask=int(b['ask'])
                spreads.append((ask-bid)/((ask+bid)/2))
                depths.append(min(int(b['bid_depth_2pct']),int(b['ask_depth_2pct']))/100)
    single=next(a for a in r['accounts'] if a['owner']=='swift-early-single')
    return dict(seed=r['seed'],threads=r['threads'],accounts=len(r['accounts']),engine_seconds=r['wall_seconds'],
        wall_seconds=json.loads(dest.with_suffix('.done.json').read_text(encoding='utf-8'))['wall_seconds'],
        audits=r['audits'],skipped=sum(a['stats']['skipped'] for a in r['accounts']),
        bot_errors=sum(a['stats']['bot_errors'] for a in r['accounts']),disabled=sum(bool(a['disabled']) for a in r['accounts']),
        quality=r['quality'],stocks=stocks,two_sided=both/max(1,samples),
        median_spread=stats.median(spreads) if spreads else None,
        median_depth_yuan=stats.median(depths) if depths else None,
        single=dict(initial_equity=single['initial_equity'],return_pct=(single['return_ratio']-1)*100,stats=single['stats']),
        world_fingerprint=dict(news_sha256=digest(dest/'news.csv'),rates_sha256=hashlib.sha256(json.dumps(rates).encode()).hexdigest(),terminal_payments=r['terminal_payments']))


def report(out,conditions,seeds,holdout=False):
    all_results={};summary={}
    for key in conditions:
        worlds=[]
        for dest in sorted((out/key).glob('seed-*-repeat-*')):
            if not dest.is_dir() or not dest.with_suffix('.done.json').exists():continue
            if int(dest.name.split('-')[1]) not in seeds:continue
            if json.loads(dest.with_suffix('.done.json').read_text(encoding='utf-8'))['exit_code']:
                raise SystemExit(f'Failed run: {dest}')
            worlds.append(measure(dest))
        missing=set(seeds)-{w['seed'] for w in worlds}
        if missing:raise SystemExit(f'{key}: missing seeds {sorted(missing)}')
        all_results[key]=worlds
        stocks=[s for w in worlds for s in w['stocks']]
        if not worlds:continue
        summary[key]=dict(worlds=len(worlds),account_range=[min(w['accounts'] for w in worlds),max(w['accounts'] for w in worlds)],
            quality_pass=sum(w['quality']['pass'] for w in worlds),skipped=sum(w['skipped'] for w in worlds),
            bot_errors=sum(w['bot_errors'] for w in worlds),disabled=sum(w['disabled'] for w in worlds),
            median_wall_seconds=stats.median(w['wall_seconds'] for w in worlds),
            median_engine_seconds=stats.median(w['engine_seconds'] for w in worlds),
            mean_two_sided=stats.mean(w['two_sided'] for w in worlds),
            median_spread=stats.median(w['median_spread'] for w in worlds),
            median_depth_yuan=stats.median(w['median_depth_yuan'] for w in worlds),
            median_close_jump_p99=stats.median(s['close_jump_p99'] for s in stocks),
            stock_worlds=len(stocks),
            doubling_stock_worlds={str(h):sum(s[f'max_rise_{h}']>=2 for s in stocks) for h in [50,100,500,3000]},
            median_max_rise={str(h):stats.median(s[f'max_rise_{h}'] for s in stocks) for h in [50,100,500,3000]},
            single_mean_return_pct=stats.mean(w['single']['return_pct'] for w in worlds),
            single_losses=sum(w['single']['return_pct']<0 for w in worlds))
    # Confirm changing account populations did not change exogenous news/dividends.
    by_seed={}
    for worlds in all_results.values():
        for w in worlds:
            if w['seed'] in by_seed:assert w['world_fingerprint']==by_seed[w['seed']],w['seed']
            by_seed[w['seed']]=w['world_fingerprint']
    result=dict(summary=summary,worlds=all_results,worlds_matched=True)
    write(out/('holdout-report.json' if holdout else 'screen-report.json'),result)
    print(json.dumps(summary,ensure_ascii=False,indent=2))


def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('command',choices=['prepare','run','report'])
    p.add_argument('--out',type=Path,default=DEFAULT);p.add_argument('--conditions',default='before,small,triple,liquid')
    p.add_argument('--source',type=Path,default=ROOT/'scenarios/baseline-v6-pre-expansion.toml',
                   help='Frozen pre-expansion baseline, used only by prepare')
    p.add_argument('--holdout',action='store_true');p.add_argument('--repeat',type=int,default=0)
    args=p.parse_args()
    if os.name=='nt':windows_build_budget()
    if args.command=='prepare':prepare(args.out,args.source);return
    plan=json.loads((args.out/'plan.json').read_text(encoding='utf-8'))
    conditions=args.conditions.split(',');seeds=plan['holdout_seeds'] if args.holdout else plan['seeds']
    if args.command=='run':run(args.out,conditions,seeds,args.repeat)
    else:report(args.out,conditions,seeds,args.holdout)


if __name__=='__main__':main()
