"""Frozen-parameter market stress suite. Python 3.11+, no third-party packages.

prepare writes an immutable experiment plan; run executes it serially/resumably;
report is in swift_stress_report.py. No strategy selection or parameter fitting.
"""
import argparse
import copy
from datetime import datetime, timezone
import hashlib
import json
from pathlib import Path
import subprocess
import tomllib

ROOT = Path(__file__).resolve().parents[1]
SCENARIOS = ROOT / "scenarios/swift-stress"
DEFAULT_OUT = ROOT / "runs/swift-stress-20261018"


def sha(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def toml_text(data):
    lines = ["# Generated by tools/swift_stress.py; the original v5 is unchanged."]

    def scalar(value):
        if isinstance(value, dict):
            return "{ " + ", ".join(f"{k} = {scalar(v)}" for k, v in value.items()) + " }"
        if isinstance(value, list):
            return "[" + ", ".join(map(scalar, value)) + "]"
        return json.dumps(value, ensure_ascii=False, allow_nan=False)

    def table(obj, prefix=""):
        for k, v in obj.items():
            if not isinstance(v, dict) and not (isinstance(v, list) and v and isinstance(v[0], dict)):
                lines.append(f"{k} = {scalar(v)}")
        for k, v in obj.items():
            name = f"{prefix}.{k}" if prefix else k
            if isinstance(v, dict):
                lines.extend(["", f"[{name}]"])
                table(v, name)
            elif isinstance(v, list) and v and isinstance(v[0], dict):
                for item in v:
                    lines.extend(["", f"[[{name}]]"])
                    table(item, name)

    table(data)
    text = "\n".join(lines) + "\n"
    assert tomllib.loads(text) == data, "TOML round trip changed a scenario"
    return text


def make_cases():
    base = tomllib.loads((ROOT / "scenarios/baseline.toml").read_text(encoding="utf-8"))
    cases = []

    def add(key, label, group="market", changes=None, **kwargs):
        cfg = copy.deepcopy(base)
        for path, value in (changes or {}).items():
            target = cfg
            parts = path.split(".")
            for part in parts[:-1]:
                target = target[part]
            target[parts[-1]] = value
        case = {"key": key, "label": label, "group": group,
                "changes": changes or {}, "cash": 2_000_000, "shares": 20,
                "params": "", "every": 1, **kwargs}
        cases.append((case, cfg))
        return cfg

    add("v5", "原版 v5")
    low = {"world.seasons.calm_to_turbulent": 0.0}
    for layer in ["market", "sector", "stock"]:
        low[f"world.news.{layer}.change_sd"] = base["world"]["news"][layer]["change_sd"] * .35
        low[f"world.news.{layer}.events_per_1000_ticks"] = base["world"]["news"][layer]["events_per_1000_ticks"] * .5
    add("calm", "低消息频率、低波动", changes=low)
    add("turbulent", "持续高波动", changes={"world.seasons.calm_to_turbulent": 1.0,
                                               "world.seasons.turbulent_to_calm": 0.0})
    add("no_news", "关闭新消息冲击", changes={f"world.news.{l}.events_per_1000_ticks": 0.0 for l in ["market", "sector", "stock"]})
    add("public_news", "消息立即同时公开", changes={"world.news.disclosure.stages": [[0, 1.0]],
                                                      "world.news.disclosure.range_widths": []})
    add("slow_news", "消息传播慢四倍", changes={"world.news.disclosure.lead_ticks": 480,
        "world.news.disclosure.stages": [[0, .05], [120, .25], [240, 1.0]]})
    no_grid = add("no_grid", "移除大资金网格对手", note="Only grid counts become zero; remaining group indices and count draws are preserved.")
    no_grid["bots"][0]["count"] = 0
    no_grid["bots"][0]["count_max"] = 0
    strong = add("strong_crowd", "弱策略换成估值强手", note="Replace momentum/news/noise/hold by astra_a/astra_b/astra_c/fund, preserving counts and endowments.")
    mapping = {"momentum": "astra_a", "news": "astra_b", "noise": "astra_c", "hold": "fund"}
    for bot in strong["bots"]:
        bot["bot"] = mapping.get(bot["bot"], bot["bot"])
    crowded = add("crowded", "增加十个 Swift 对手", note="Adds ten exact default Swift copies; crowd size and wealth both increase.")
    crowded["bots"].append({"bot": "swift", "count": 10, "cash": 2_000_000, "shares_each": 20})
    add("fee20", "手续费每边 20 bp", changes={"fees.trade_fee_bps": 20})
    add("fee50", "手续费每边 50 bp", changes={"fees.trade_fee_bps": 50})
    add("no_idle", "取消闲置费及交易抵扣", changes={"fees.idle_rate": 0.0, "fees.credit_ratio": 0.0})
    add("tick10", "最小报价单位十倍", changes={"market.tick_size": 10})
    add("depth1", "所有人只看一档盘口", changes={"market.book_depth": 1})
    add("capital01", "本金 0.1 倍", "capacity", cash=200_000, shares=2)
    add("capital10", "本金 10 倍", "capacity", cash=20_000_000, shares=200)
    add("capital100", "本金 100 倍", "capacity", cash=200_000_000, shares=2000)
    add("cash_start", "等初始权益、纯现金开局", "capacity", cash_reference=True,
        note="Cash equals the matched v5 world's initial challenger equity; no initial shares.")
    add("cadence5", "每五 tick 决策一次", "cadence", every=5)
    add("cadence20", "每二十 tick 决策一次", "cadence", every=20)
    add("flow_only", "只保留主动成交信号", "ablation", params="depth=0,momentum=0")
    add("no_depth", "去掉盘口信号", "ablation", params="depth=0")
    add("no_momentum", "去掉动量信号", "ablation", params="momentum=0")
    add("no_signal_exit", "关闭信号清仓", "ablation", params="exit=-2",
        note="Position sizing and final-20-tick exit remain active; only the negative-signal exit is disabled.")
    add("unlevered", "不使用杠杆", "ablation", params="leverage=1")
    add("cash_control", "卖出初始股票后不再买入", "control", params="entry=100,exit=100")
    add("v5_repeat", "原版 v5 同种子重复", "repeat")
    return cases


def prepare(out):
    if (out / "plan.json").exists():
        raise SystemExit("Plan already exists; use run to resume.")
    binary = ROOT / "target/release/swift-eval.exe"
    old = json.loads((ROOT / "docs/swift-v5-results.json").read_text())
    old_manifest = old["batches"][-1]["source_manifest"]
    for rel, digest in old_manifest.items():
        if rel.replace("\\", "/").startswith(("crates/bots/", "crates/market/")):
            assert sha(ROOT / rel) == digest, f"Frozen strategy/engine changed: {rel}"
    SCENARIOS.mkdir(exist_ok=True)
    cases = []
    for case, cfg in make_cases():
        path = SCENARIOS / f"{case['key']}.toml"
        text = toml_text(cfg)
        path.write_text(text, encoding="utf-8")
        case["scenario"] = path.relative_to(ROOT).as_posix()
        case["scenario_sha256"] = sha(path)
        cases.append(case)
    confirm = ["v5", "turbulent", "public_news", "no_grid", "strong_crowd", "crowded", "fee50", "capital100"]
    jobs = [{"id": f"a-{c['key']}", "case": c["key"], "first_seed": 7001, "seeds": 20} for c in cases]
    jobs += [{"id": f"b-{key}", "case": key, "first_seed": 8001, "seeds": 20} for key in confirm]
    sources = sorted((ROOT / "crates").rglob("*.rs")) + sorted((ROOT / "crates").rglob("Cargo.toml"))
    sources += [ROOT / "Cargo.toml", ROOT / "Cargo.lock", Path(__file__)]
    plan = {"created_utc": datetime.now(timezone.utc).isoformat(), "strategy_frozen_commit": "5289b76",
            "binary": binary.relative_to(ROOT).as_posix(), "binary_sha256": sha(binary),
            "sources": {p.relative_to(ROOT).as_posix(): sha(p) for p in sources},
            "cases": cases, "jobs": jobs, "world_runs": sum(j["seeds"] for j in jobs),
            "gate": {"mean_percentile": 90, "top_quartile_share": .8},
            "notes": ["No Swift tuning; ablations are labeled controls, not replacement candidates.",
                      "Common seed IDs do not imply identical price paths after changing agents or market rules.",
                      "Equity is observed before decisions; mark-based drawdown differs from executable liquidation value.",
                      "Cadence is decision frequency, not network or exchange latency.",
                      "All scenarios share this dividend-driven simulator; this is not real-market validation."]}
    out.mkdir(parents=True, exist_ok=True)
    (out / "plan.json").write_text(json.dumps(plan, ensure_ascii=False, indent=2)+"\n", encoding="utf-8")
    print(f"Prepared {len(cases)} cases, {len(jobs)} batches, {plan['world_runs']} world-runs.")


def run(out):
    plan = json.loads((out / "plan.json").read_text(encoding="utf-8"))
    for rel, digest in plan["sources"].items():
        assert sha(ROOT / rel) == digest, f"Source changed after freezing: {rel}"
    assert sha(ROOT / plan["binary"]) == plan["binary_sha256"]
    cases = {c["key"]: c for c in plan["cases"]}
    for job in plan["jobs"]:
        case = cases[job["case"]]
        assert sha(ROOT / case["scenario"]) == case["scenario_sha256"]
        dest = out / job["id"]
        if (dest / "done.json").exists():
            continue
        if dest.exists():
            raise SystemExit(f"Incomplete batch {dest}; preserve and investigate it before resuming.")
        cmd = [str(ROOT / plan["binary"]), str(ROOT / case["scenario"]), "--out", str(dest),
               "--first-seed", str(job["first_seed"]), "--seeds", str(job["seeds"]),
               "--cash", str(case["cash"]), "--shares", str(case["shares"]), "--every", str(case["every"])]
        if case["params"]:
            cmd += ["--params", case["params"]]
        if case.get("cash_reference"):
            cmd += ["--cash-reference", str(out / "a-v5")]
        print(f"START {job['id']}: {case['label']}", flush=True)
        with (out / f"{job['id']}.log").open("w", encoding="utf-8") as log:
            subprocess.run(cmd, cwd=ROOT, stdout=log, stderr=subprocess.STDOUT, check=True)
        p, returns = [], []
        for seed in range(job["first_seed"], job["first_seed"]+job["seeds"]):
            summary = json.loads((dest / f"seed-{seed}/summary.json").read_text())
            a = next(a for a in summary["accounts"] if a["owner"] == "challenger")
            p.append(a["percentile"])
            returns.append((a["return_ratio"]-1)*100)
        record = {"job": job, "case": case, "command": cmd, "binary_sha256": plan["binary_sha256"],
                  "mean_percentile": sum(p)/len(p), "top25": sum(x >= 75 for x in p)/len(p),
                  "mean_return_pct": sum(returns)/len(returns), "loss_worlds": sum(x < 0 for x in returns)}
        (dest / "done.json").write_text(json.dumps(record, ensure_ascii=False, indent=2)+"\n", encoding="utf-8")
        print(f"DONE {job['id']}: rank={record['mean_percentile']:.2f}, top25={record['top25']:.0%}, return={record['mean_return_pct']:.1f}%, losses={record['loss_worlds']}/{len(p)}", flush=True)


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("mode", choices=["prepare", "run"])
    p.add_argument("--out", type=Path, default=DEFAULT_OUT)
    a = p.parse_args()
    {"prepare": prepare, "run": run}[a.mode](a.out.resolve())


if __name__ == "__main__":
    main()
